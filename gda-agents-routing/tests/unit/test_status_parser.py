def test_custom_status_parser_thought() -> None:
    agent = _create_mock_gda_agent()
    session_service = InMemorySessionService()
    session = session_service.create_session_sync(user_id="test_user", app_name="test_app")
    ctx = InvocationContext(session=session, session_service=session_service, invocation_id="inv-1")

    payload = {
        "status": {
            "state": "TASK_STATE_WORKING",
            "message": {
                "parts": [
                    {
                        "text": "Thinking about coffee sales...",
                        "metadata": {"gda_message": {"subType": "thought"}},
                    }
                ]
            },
        }
    }
    event_proto = json_format.ParseDict(
        payload, TaskStatusUpdateEvent(), ignore_unknown_fields=True
    )
    adk_event = agent.custom_status_parser(
        update=event_proto,
        agent_name=agent.name,
        ctx=ctx,
        part_converter=MagicMock(),
    )

    assert adk_event is not None
    assert len(adk_event.content.parts) == 1
    assert adk_event.content.parts[0].text == "Thinking about coffee sales..."
    assert getattr(adk_event.content.parts[0], "thought", False) is True
